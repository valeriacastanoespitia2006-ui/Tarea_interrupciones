/**
  * @brief  Revisa si llegó un caracter por el USART y controla el LED5.
  *         Lee directamente el registro de datos (sin DMA, sin IDLE),
  *         que es lo que mejor funciona en la simulación de Proteus.
  *           '1' -> prende LED5
  *           '0' -> apaga  LED5
  *         Cualquier otro caracter (\r, \n, espacios...) se ignora.
  */
void revisar_serial(UART_HandleTypeDef *huart)
{
  uint32_t sr = huart->Instance->SR;

  // RXNE = llegó un dato; ORE = se perdió uno (igual hay que leer DR para limpiarlo)
  if (sr & (USART_SR_RXNE | USART_SR_ORE))
  {
    char c = (char)(huart->Instance->DR & 0xFF);   // leer DR limpia RXNE y ORE

    if (c == '1')
    {
      HAL_GPIO_WritePin(LED5_GPIO_Port, LED5_Pin, GPIO_PIN_SET);
      uartx_write_text(huart, "LED5 ON\r\n");
    }
    else if (c == '0')
    {
      HAL_GPIO_WritePin(LED5_GPIO_Port, LED5_Pin, GPIO_PIN_RESET);
      uartx_write_text(huart, "LED5 OFF\r\n");
    }
  }
}

